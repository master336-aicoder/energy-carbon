
USE energy_carbon;

-- 操作日志新增字段
ALTER TABLE sys_log
ADD COLUMN IF NOT EXISTS browser VARCHAR(100) DEFAULT NULL COMMENT '浏览器信息',
ADD COLUMN IF NOT EXISTS os VARCHAR(100) DEFAULT NULL COMMENT '操作系统信息',
ADD COLUMN IF NOT EXISTS referer VARCHAR(500) DEFAULT NULL COMMENT '来源页面',
ADD COLUMN IF NOT EXISTS user_agent VARCHAR(500) DEFAULT NULL COMMENT '用户代理';

-- AI服务预约记录表
CREATE TABLE IF NOT EXISTS ai_service_record (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
  service_name VARCHAR(200) DEFAULT NULL COMMENT '服务名称',
  contact_name VARCHAR(100) DEFAULT NULL COMMENT '联系人',
  contact_phone VARCHAR(20) DEFAULT NULL COMMENT '联系电话',
  appointment_date DATE DEFAULT NULL COMMENT '预约日期',
  status VARCHAR(20) DEFAULT 'PENDING' COMMENT '状态',
  remark TEXT DEFAULT NULL COMMENT '备注',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI服务预约记录表';

-- 通知公告表
CREATE TABLE IF NOT EXISTS sys_notice (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
  notice_title VARCHAR(200) NOT NULL COMMENT '公告标题',
  notice_content TEXT COMMENT '公告内容',
  notice_type TINYINT DEFAULT 1 COMMENT '类型（1通知 2公告）',
  status TINYINT DEFAULT 1 COMMENT '状态（1正常 0关闭）',
  create_by BIGINT DEFAULT NULL COMMENT '创建人ID',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by BIGINT DEFAULT NULL COMMENT '更新人ID',
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='通知公告表';

-- 通知下发记录表
CREATE TABLE IF NOT EXISTS sys_notice_dispatch (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
  notice_id BIGINT NOT NULL COMMENT '关联通知公告ID',
  user_id BIGINT NOT NULL COMMENT '接收用户ID',
  read_status TINYINT DEFAULT 0 COMMENT '阅读状态（0未读 1已读）',
  read_time DATETIME DEFAULT NULL COMMENT '阅读时间',
  create_by BIGINT DEFAULT NULL COMMENT '创建人ID',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by BIGINT DEFAULT NULL COMMENT '更新人ID',
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='通知下发记录表';

-- 用户消息表
CREATE TABLE IF NOT EXISTS sys_user_message (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
  user_id BIGINT NOT NULL COMMENT '接收用户ID',
  title VARCHAR(200) NOT NULL COMMENT '消息标题',
  content TEXT COMMENT '消息内容',
  msg_type TINYINT DEFAULT 1 COMMENT '消息类型（1系统 2通知 3告警）',
  read_status TINYINT DEFAULT 0 COMMENT '阅读状态（0未读 1已读）',
  read_time DATETIME DEFAULT NULL COMMENT '阅读时间',
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户消息表';
